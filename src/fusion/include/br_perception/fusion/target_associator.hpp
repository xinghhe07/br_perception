#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace br_perception {
namespace fusion {

/**
 * @brief 观测 ↔ 追踪 的关联（模块 19）
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ⚠️⚠️ **与任务书的偏差（用户 2026-09-19 拍板，以此为准）**
 *
 * 任务书 §4.3 写的是「**实现匈牙利算法**进行二分图最优匹配」。**本模块不做匈牙利**：
 *
 * > 本项目的落点**全是已知位置**（建筑位 / 两根柱子 / 穆斯蒂卡柱），
 * > "观测 ↔ 目标"是**查表 / 落区判定**，**不需要匈牙利二分图匹配** ——
 * > 匈牙利是为"数量未知、互相匹配"准备的。
 * > 匈牙利只留给**数量未知**的场景（对手 BR / TR、掉落方块），或直接砍掉改为**就近指派**。
 *
 * ⇒ 本实现分两级，**顺序有意义**：
 *
 * | 级 | 名字 | 判据 | 适用 |
 * |---|---|---|---|
 * | **①** | **落区认领** | 观测落在某个**已知位置**的 `radius_m` 内 ⇒ **直接认领那个目标** | 建筑位 / 两根柱子 / 穆斯蒂卡柱（位置**已知**） |
 * | **②** | **就近指派** | 剩下的按三维距离**贪心**配对，带 `gate_m` 门限 | 数量未知的（对手 BR / TR / 掉落方块） |
 *
 * ⚠️ **① 优先于 ②，这是本模块的核心语义**：一个观测可能离 track A 更近，但它**落在
 *    track B 的已知区域内** ⇒ **必须认 B**。理由：A 的位置是**滤波估计**（会被运动/噪声带偏），
 *    而 B 的位置是**场地事实**（常量）。拿估计值去压常量 = 把唯一确定的东西弄丢。
 *    ⚠️ 若改成"纯就近"，症状是**建筑位归属偶尔串位** —— 不报错，只在特定位姿下偶发。
 *
 * ⚠️ **本模块是纯函数**（static，不起节点、不碰 ROS 消息）⇒ 可被 `test/` 直接喂。
 *    话题订阅/发布由模块 21 `fusion_node` 负责。
 *
 * ⚠️ **本模块不做时间同步** —— 规格 §4.4 要求的那件事（找时间戳最接近的雷达帧/相机帧配对）
 *    归 `lidar_camera_fusion`，不在这里。
 */
class TargetAssociator
{
public:
  // ══════════════════════════════════════════════════════════════════════
  // 数据（**只用自有 POD**，不引 ROS 消息 —— 保持可单测）
  // ══════════════════════════════════════════════════════════════════════

  /// 一次观测（单帧）。⚠️ 与 `Track` 是两回事：`Track` 是跨帧的目标。
  struct Observation
  {
    std::uint32_t id{0};
    double x{0.0}, y{0.0}, z{0.0};
    float  confidence{0.0f};
    std::uint8_t type{0};        ///< 沿用 `Obstacle.msg` 的 ObstacleType
    std::uint8_t source{0};      ///< 1=雷达 2=相机（见 `Track.msg` 的 SRC_*）
    bool   is_held{false};       ///< 「v1.3」持握：夹爪粘连/悬空 ⇒ 3D 不可靠
  };

  /// 一个已有追踪（**只取关联用得到的字段** —— 别把整个滤波器搬进来）
  struct Track
  {
    std::uint32_t id{0};
    double x{0.0}, y{0.0}, z{0.0};
    float  confidence{0.0f};
    std::uint8_t type{0};
    /// 「v1.3」持握目标。⚠️ **不参与雷达关联**：雷达点云与夹爪粘连、或方块不在建筑位上方
    /// 被 `building_spot_analyzer` 忽略 ⇒ 拿雷达去"纠正"它只会把它拽错。
    bool   is_held{false};

    /// ⚠️⚠️ **它是不是"已知位置"上的常驻目标**（建筑位 / 柱子 / 穆斯蒂卡柱）。
    ///
    /// 置位后，这个 track **只接受【落区认领】，不参与【就近指派】**。
    /// ⚠️ 为什么（2026-09-25 端到端实测抓出）：
    ///    一个敌方机器人位于 `(7.0, 7.0)`，L2 建筑位在 `(6.75, 6.75)`
    ///    ⇒ 距离 0.354m —— **没进 0.35m 的认领区，却进了 0.6m 的就近门限**
    ///    ⇒ **被就近指派给了那个静态建筑位** ⇒ 它不再是移动目标
    ///    ⇒ **`BR_RESET` 也清不掉它**（规则的"清移动目标"对它失效）。
    ///
    /// ⚠️ 根因与类型门控那条同源：**已知位置是静态的，它只该被"落在它区域里"的观测认领**，
    ///    不该因为"离得近"就去抢一个会动的目标。
    bool   is_known_position{false};
  };

  /// **已知位置**（场地事实：建筑位 / 两根柱子 / 穆斯蒂卡柱）
  /// ⚠️ 这些是**常量**，来源是 `config/field_geometry.yaml`；**不要拿滤波估计值来填**。
  struct KnownRegion
  {
    std::uint32_t track_id{0};
    double x{0.0}, y{0.0}, z{0.0};
    double radius_m{0.0};   ///< 水平半径（**只看 xy**，见实现里的 ⚠️）
  };

  struct Params
  {
    /// 就近指派的门限（m）。超过它**不关联** ⇒ 该观测应去建新候选，而不是硬塞给最近的 track。
    /// ⚠️ 设太大 = 把噪声塞进已有目标（**假阳性**）；设太小 = 真目标每次都被当新的（**ID 跳变**）。
    double gate_m{0.60};
    /// 落区认领的**兜底**半径，仅当 `KnownRegion::radius_m <= 0` 时用它
    double default_region_m{0.35};
    /// 「v1.3」持握目标是否拒绝**雷达**观测的关联
    bool hold_rejects_lidar{true};

    /// **允许被【落区认领】的观测类型**（取值 = `Obstacle.msg` 的 `ObstacleType`）。
    ///
    /// ⚠️⚠️ **默认不含 `ENEMY_ROBOT(3)`** —— 2026-09-25 实测抓出来的：
    ///    一个敌方机器人位于 `(3.0, 3.0)`，而建筑位在 `(2.8, 2.8)`
    ///    ⇒ 距离 **0.283m < 0.35m 的认领半径** ⇒ **被那个静态建筑位认领走了**
    ///    ⇒ 它**不再是"移动目标"** ⇒ **`BR_RESET` 也清不掉它**。
    ///
    /// ⚠️ 根因：落区认领那条路**只看了位置，没看类型**。
    ///    而"已知位置"是**静态**的（建筑位 / 柱子 / 穆斯蒂卡柱）——
    ///    一个**会动的**目标落在它附近，**不等于它属于那个位**。
    ///    ⇒ 按类型门控：只有"可能被放在已知位置上"的类型才允许被认领。
    ///    （`0 = UNKNOWN` 也放进来 —— "还没分类出来"不该因此丢掉落区信息。）
    std::vector<std::uint8_t> region_claim_types{0, 1, 2, 4};
  };

  /// 一条匹配。`track_index < 0` 表示**未匹配**（调用方据此建新候选 track）。
  struct Match
  {
    int    obs_index{-1};
    int    track_index{-1};
    double cost{0.0};           ///< 三维距离（m）；落区认领时为到区域中心的距离
    bool   by_region{false};    ///< true = 这一条是**落区认领**（①），false = 就近指派（②）
  };

  // ══════════════════════════════════════════════════════════════════════
  // 核心：关联
  // ══════════════════════════════════════════════════════════════════════

  /// @brief 把观测关联到已有追踪
  /// @return 与 `obs` **等长、同序**的匹配数组（每条观测一条结果，未匹配的 `track_index = -1`）。
  ///         ⚠️ **等长同序**是有意的：调用方按 `obs[i]` 直接取 `result[i]`，不用查表。
  ///         若改成"只返回匹配上的"，调用方就得自己判断哪条观测没配上 —— 那是**漏建候选 track** 的温床。
  ///
  /// ⚠️ **一对一**：一个 track 最多被一条观测认领（先到先得，按下面的顺序）。
  /// ⚠️ 处理顺序：**先落区（①）再就近（②）**；同级内按 `cost` 升序贪心。
  [[nodiscard]] static std::vector<Match> associate(
      const std::vector<Observation>& obs,
      const std::vector<Track>& tracks,
      const std::vector<KnownRegion>& known,
      const Params& params);

  /// @brief 三维欧氏距离（关联判据；**不要换成曼哈顿/平方距离** —— 门限是按米标定的）
  [[nodiscard]] static double distance3d(double ax, double ay, double az,
                                         double bx, double by, double bz);

  /// @brief 观测是否落在某个已知区域内（**只看水平 xy**）
  ///
  /// ⚠️ **刻意不判 z**：建筑位/柱子的 z 是**平台高**，而观测的 z 受俯仰误差与遮挡影响
  ///    远大于 xy（雷达在斜视角下对 z 的估计最差）。带上 z 会让"明明就在那个位上"的观测
  ///    频繁认领失败。⚠️ 代价是**正上方/正下方**的观测也会被认领 —— 对场地布局可接受。
  [[nodiscard]] static bool in_region(double x, double y,
                                      const KnownRegion& region,
                                      double default_radius_m);

  [[nodiscard]] static const char* source_name(std::uint8_t source);
};

}  // namespace fusion
}  // namespace br_perception
